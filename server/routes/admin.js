import * as media from '../controllers/mediaController.js';
import { rateLimit } from '../middleware/rateLimit.js';
import { Router } from 'express';
import * as c from '../controllers/adminController.js';
import * as s from '../controllers/storeController.js';
import * as o from '../controllers/orderController.js';
import { verifyToken, isStaff, isAdmin } from '../middleware/authMiddleware.js';
import { route } from '../utils/validation.js';
const r = Router();
r.use(verifyToken, isStaff);
r.get('/media', route(media.listMedia));
r.post('/media/sign', rateLimit('media-upload', 40), route(media.signUpload));
r.post('/media/:id/complete', route(media.completeUpload));
r.patch('/media/:id/archive', route(media.archiveMedia));
r.delete('/media/:id', route(media.deleteMedia));
r.get('/metrics', route(c.getOverviewMetrics));
r.get('/settings', route(s.publicSettings));
r.put('/settings', route(s.updateSettings));
r.get('/inquiries', route(s.getInquiries));
r.patch('/inquiries/:id/resolve', route(s.resolveInquiry));
r.get('/password-requests', isAdmin, route(c.getPasswordRequests));
r.post('/password-requests/:id/fulfill', isAdmin, route(c.fulfillPasswordRequest));
r.post('/users/:id/set-password', isAdmin, route(c.setUserPasswordManually));
r.get('/users', isAdmin, route(c.getAllUsers));
r.post('/users', isAdmin, route(c.createUser));
r.get('/users/:id', isAdmin, route(c.getUserById));
r.put('/users/:id', isAdmin, route(c.updateUser));
r.patch('/users/:id/ban', isAdmin, route(c.banUser));
r.patch('/users/:id/unban', isAdmin, route(c.unbanUser));
r.delete('/users/:id', isAdmin, route(c.softDeleteUser));
r.patch('/users/:id/restore', isAdmin, route(c.restoreUser));
r.get('/products', route(c.getAllProductsAdmin));
r.post('/products', route(c.createProduct));
r.put('/products/:id', route(c.updateProduct));
r.patch('/products/:id/stock', route(c.updateProductStock));
r.delete('/products/:id', route(c.softDeleteProduct));
r.patch('/products/:id/restore', route(c.restoreProduct));
r.get('/order-notifications', route(c.getOrderNotifications));
r.get('/orders', route(c.getAllOrders));
r.get('/orders/:id', route(c.getAdminOrder));
r.patch('/orders/:id/status', route(o.updateOrderStatus));
r.patch('/orders/:id/payment', route(o.updatePaymentStatus));
export default r;
