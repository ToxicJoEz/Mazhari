import { Router } from 'express';
import { register, login, forgotPassword } from '../controllers/authController.js';
import { route } from '../utils/validation.js';
import { rateLimit } from '../middleware/rateLimit.js';
const router = Router();
router.use(rateLimit('accounts', 50));
router.post('/register', route(register));
router.post('/login', route(login));
router.post('/forgot-password', route(forgotPassword));
export default router;
